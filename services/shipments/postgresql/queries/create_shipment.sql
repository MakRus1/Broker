INSERT INTO shipments (
    organization_id,
    number,
    customer_id,
    reference,
    shipment_date,
    recipient_id,
    logist,
    cargo_description,
    status,
    incoterms,
    carriage_terms,
    loading,
    delivery_city,
    delivery_country,
    delivery_address,
    route_segments
)
SELECT
    $1::UUID,
    card.number,
    card.customer_id,
    card.reference,
    card.shipment_date::DATE,
    card.recipient_id,
    card.logist,
    card.cargo_description,
    card.status,
    card.incoterms,
    card.carriage_terms,
    card.loading,
    card.delivery_city,
    card.delivery_country,
    card.delivery_address,
    card.route_segments
FROM (SELECT ($2::public.shipment_data_v2).*) AS card
RETURNING ROW(
    id,
    revision,
    number,
    customer_id,
    reference,
    shipment_date::TEXT,
    recipient_id,
    logist,
    cargo_description,
    status,
    incoterms,
    carriage_terms,
    loading,
    delivery_city,
    delivery_country,
    delivery_address,
    route_segments
)::public.shipment_v3;
