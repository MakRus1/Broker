-- $1 — организация.
-- $2 — область ключа.
-- $3 — строковый ключ (NULL, если передан UUID).
-- $4 — UUID источника (NULL, если передан строковый ключ).
-- Одинаковый ключ сериализуется между репликами до изменения бизнес-данных.
SELECT pg_advisory_xact_lock(hashtextextended(
    $1::UUID::TEXT || ':' || $2 || ':' || COALESCE($3, $4::UUID::TEXT), 0
));
