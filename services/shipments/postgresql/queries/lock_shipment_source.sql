-- $1 — организация.
-- $2 — сервис-источник.
-- $3 — тип источника.
-- $4 — UUID источника сервисной команды.
-- $5 — ключ идемпотентности ручного создания.
-- Формат ключа совпадает с прежней блокировкой по источнику.
SELECT pg_advisory_xact_lock(hashtextextended(
    $1::UUID::TEXT || ':' || $2 || ':' || $3 || ':' || COALESCE($4::UUID::TEXT, $5), 0
));
